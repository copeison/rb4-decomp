// Reconstructed from eboot.elf at 0x65C1A0. The glyphs are the printable
// ASCII characters from '!' and a final U+25A0 block, each 7 pixels wide on
// an 8 by 8 tile.
void RndDebugFont::Init() {
    gDebugFont = new RndFont;
    gDebugFont->mName = Symbol("Debug");

    const Vector2i& resolution = TheRndDevice()->mSettings->mOutputResolution;
    gDebugFont->AddResolution(resolution);
    gDebugFont->mFlags = 1;
    gDebugFont->SetGlyphTileSizeInPixels(resolution, Vector2i{8, 8});
    gDebugFont->SetGlyphSpacingInPixels(resolution, Vector2i{1, 3});
    gDebugFont->SetGlyphHeightInPixels(resolution, 8);
    gDebugFont->SetSpaceSizeInPixels(resolution, 7);
    gDebugFont->SetNumPages(resolution, 1);

    RndFontPage& page = gDebugFont->GetSize(resolution)->mPages[0];
    page.SetTexture(_CreateTexture());
    page.SetNumGlyphs(kNumGlyphs);
    for (unsigned long glyph = 0; glyph < kNumGlyphs; ++glyph) {
        const unsigned short character =
            glyph == kNumGlyphs - 1 ? 0x25A0 : static_cast<unsigned short>(glyph + '!');
        page.SetGlyph(glyph, character, 7, 0, 7, Vector2i{kTextureWidth, kTextureHeight});
    }
    gDebugFont->Finalize();
}

// Reconstructed from eboot.elf at 0x65C4E0. Rows past the bitmap stay
// transparent.
RndTexture2D* RndDebugFont::_CreateTexture() {
    RndPixelCanvas canvas;
    canvas.CreateUninitialized(kTextureWidth, kTextureHeight, 1);
    for (int row = 0; row < kNumBitmapRows; ++row) {
        for (int x = 0; x < kTextureWidth; ++x) {
            const unsigned char bits = gBitmapData[row * 8 + x / 8];
            const bool set = ((bits >> (~x & 7)) & 1) != 0;
            canvas.mPixels[row * canvas.mWidth + x] =
                set ? Hmx::Color::GetWhite() : Hmx::Color::GetZero();
        }
    }
    for (int row = kNumBitmapRows; row < kTextureHeight; ++row) {
        for (int x = 0; x < kTextureWidth; ++x) {
            canvas.mPixels[row * canvas.mWidth + x] = Hmx::Color::GetZero();
        }
    }

    RndTexture2D::Description desc;
    // An 8-bit single-channel linear format.
    const RndDataFormatInfo info{8, 10, 0, 1, -1};
    const int dataFormat = RndFindSupportedDataFormat(info, kPlatformPS4);
    desc.mRequestedFormat.mWrapMode = 1;
    desc.mRequestedFormat.mFilterMode = 1;
    desc.mName = "Debug Font";
    desc.mPixels.CreateEmpty(kTextureWidth, kTextureHeight, 1, dataFormat);
    desc.mPixels.ConvertFrom(canvas);
    return RndTexture2D::New(desc);
}

// Reconstructed from eboot.elf at 0x65C790.
void RndDebugFont::Terminate() {
    delete gDebugFont;
    gDebugFont = nullptr;
}

// Reconstructed from eboot.elf at 0x65C7D0.
RndFont* RndDebugFont::GetInstance() {
    return gDebugFont;
}

// Reconstructed from eboot.elf at 0x65CAF0. Each entry of the language's
// list is (path enabled).
void RndDebugFont::InitExtendedFonts() {
    DataArray* config = SystemConfig(Symbol("rnd"), Symbol("font"));
    const Symbol extendedFonts("extended_fonts");
    const Symbol language = SystemLanguage();
    DataArray* languages = config->FindArray(extendedFonts, false);
    if (languages == nullptr) {
        return;
    }
    DataArray* fonts = languages->FindArray(language, false);
    if (fonts == nullptr) {
        return;
    }

    const unsigned long count = static_cast<unsigned int>(fonts->Size() - 1);
    gExtendedFonts.resize(count);
    for (unsigned long i = 0; i < count; ++i) {
        DataArray* entry = fonts->Node(i + 1).Array(fonts);
        if (entry->Int(1) != 0) {
            gExtendedFonts[i] = Resource::GetOrLoad<RndFontResource>(
                ResourcePath(entry->Str(0)), false);
        }
    }
}

// Reconstructed from eboot.elf at 0x65CE70.
void RndDebugFont::TerminateExtendedFonts() {
    gExtendedFonts.clear();
}

// Reconstructed from eboot.elf at 0x65CEC0.
bool RndDebugFont::HasExtendedFonts() {
    return !gExtendedFonts.empty();
}
