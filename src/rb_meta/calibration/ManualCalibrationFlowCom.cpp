// Reconstructed from eboot.elf at 0xDB9A60. The meta state's calibration
// user counts as the flow's user too.
DataNode ManualCalibrationFlowCom::OnMsg(const UIButtonDownMsg& msg) {
    const int action = msg.GetAction();
    static_cast<void>(msg.GetUser());
    const int padNum = msg.GetPadNum();
    if (padNum != mFlowPadNum) {
        const User* const user = theRBMetaState.mCalibrationUser;
        if (user == nullptr || padNum != user->GetPadNum()) {
            return DataNode();
        }
    }
    static Symbol calibrationFlow;
    if (calibrationFlow == Symbol()) {
        calibrationFlow = Symbol("calibration_flow");
    }
    Message<1> flow(calibrationFlow);
    if (action == kActionCancel) {
        flow.mData->Node(2) = DataNode(kFlowBack);
    } else if (action == kActionConfirm && !mAwaitingConfirmButton) {
        flow.mData->Node(2) = DataNode(kFlowForward);
    } else if (action == kActionShellOption) {
        flow.mData->Node(2) = DataNode(kFlowShellOption);
    } else {
        return DataNode();
    }
    mObject->mEntity->Export(flow.mData);
    return DataNode(0);
}

// Reconstructed from eboot.elf at 0xDB9E60.
DataNode ManualCalibrationFlowCom::Handle(DataArray* msg, bool warn) {
    static_cast<void>(warn);
    if (msg->Sym(1) == UIButtonDownMsg::Event()) {
        DataNode result = OnMsg(UIButtonDownMsg(msg));
        if (result.Type() != kDataUnhandled) {
            return result;
        }
    }
    return DataNode();
}

